"""把 encodings 冻结进 CPython 的构建期表。

为什么必须在构建期：`Py_InitializeFromConfig` 在导入机制就绪前就要确定文件系统
编码，此时内存 zip finder 还没装上。encodings 是纯 Python 包，只能是 `_frozen`
条目。运行期改 `_PyImport_FrozenStdlib` 指针无效——FrozenImporter 读的是编译期
数组（见 docs/adr/0008）。

用法：
  python scripts/freeze_encodings.py             # 只生成 stages/python/frozen/*.h
  python scripts/freeze_encodings.py --install   # 生成 + 装进 vendor 源码树

`--install` 做两件事，重复执行结果一致：
  1. 把 122 个 .h 复制到 vendor/Python-3.11.9/Python/frozen_modules/；
  2. 在 vendor/.../Python/frozen.c 里写入 include 块与 stdlib_modules[] 条目
     （`encodings` 是包，is_package 必须为 1，否则解释器找不到文件系统编码）。

build_static_python.sh 在构建 pythoncore 之前调用 --install，因此"构建期冻结"
是可复现的，不依赖任何手工改动。
"""
import os
import re
import shutil
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VENDOR = os.path.join(ROOT, "stages", "python", "vendor", "Python-3.11.9")
FREEZE = os.path.join(VENDOR, "PCbuild", "amd64", "_freeze_module.exe")
SRC = os.path.join(VENDOR, "Lib", "encodings")
OUT_H = os.path.join(ROOT, "stages", "python", "frozen")
FROZEN_DIR = os.path.join(VENDOR, "Python", "frozen_modules")
FROZEN_C = os.path.join(VENDOR, "Python", "frozen.c")

MARK_BEGIN = "/* qf:encodings-freeze:begin (generated by scripts/freeze_encodings.py) */"
MARK_END = "/* qf:encodings-freeze:end */"


def sym(modname: str) -> str:
    return "_Py_M__" + re.sub(r"[^0-9A-Za-z_]", "_", modname)


def gen_headers():
    """用 CPython 自己的 _freeze_module 生成 marshal 头文件。"""
    if not os.path.isfile(FREEZE):
        raise SystemExit("缺少 _freeze_module.exe（先跑 build_static_python.sh 的第 1 步）: " + FREEZE)
    os.makedirs(OUT_H, exist_ok=True)

    entries = []
    for name in sorted(os.listdir(SRC)):
        if not name.endswith(".py"):
            continue
        is_pkg = name == "__init__.py"
        mod = "encodings." + name[:-3] if not is_pkg else "encodings"
        hdr = os.path.join(OUT_H, mod + ".h")
        r = subprocess.run(
            [FREEZE, mod, os.path.join(SRC, name), hdr],
            cwd=os.path.join(VENDOR, "PCbuild", "amd64"),
            capture_output=True,
            text=True,
        )
        if r.returncode != 0:
            raise SystemExit("冻结失败 %s: %s" % (mod, r.stderr.strip()))
        entries.append((mod, os.path.basename(hdr), is_pkg))
    return entries


def strip_previous(text: str) -> str:
    """去掉上一次安装的内容（含早先手工写入、没有标记的同名条目）。"""
    out = []
    skip = False
    for line in text.splitlines():
        if MARK_BEGIN in line:
            skip = True
            continue
        if MARK_END in line:
            skip = False
            continue
        if skip:
            continue
        stripped = line.strip()
        if stripped.startswith('#include "frozen_modules/encodings'):
            continue
        if re.match(r'\{"encodings(?:\.|")', stripped):
            continue
        out.append(line)
    return "\n".join(out).rstrip("\n") + "\n"


def install(entries):
    os.makedirs(FROZEN_DIR, exist_ok=True)
    for _, hdr, _ in entries:
        shutil.copyfile(os.path.join(OUT_H, hdr), os.path.join(FROZEN_DIR, hdr))

    with open(FROZEN_C, encoding="utf-8") as f:
        text = strip_previous(f.read())

    inc = [MARK_BEGIN] + ['#include "frozen_modules/%s"' % hdr for _, hdr, _ in entries] + [MARK_END]
    rows = [MARK_BEGIN]
    for mod, _, is_pkg in entries:
        rows.append('    {"%s", %s, (int)sizeof(%s), %d, NULL},'
                    % (mod, sym(mod), sym(mod), 1 if is_pkg else 0))
    rows.append(MARK_END)

    anchor = "static const struct _frozen stdlib_modules[] = {"
    if anchor not in text:
        raise SystemExit("frozen.c 里找不到 stdlib_modules[]：%s" % FROZEN_C)
    text = text.replace(anchor, "\n".join(inc) + "\n\n" + anchor, 1)

    # 条目插在 stdlib_modules 的哨兵之前（取 anchor 之后的第一个哨兵）。
    start = text.index(anchor)
    end = text.index("};", start)
    body = text[start:end]
    sentinel = re.search(r"^[ \t]*\{0, 0, 0\}", body, re.M)
    if not sentinel:
        raise SystemExit("stdlib_modules[] 缺少 {0, 0, 0} 哨兵")
    pos = start + sentinel.start()
    text = text[:pos] + "\n".join(rows) + "\n" + text[pos:]

    with open(FROZEN_C, "w", encoding="utf-8", newline="") as f:
        f.write(text)
    return len(entries)


def main(argv):
    entries = gen_headers()
    print("frozen: %d 个 encodings 模块 -> %s" % (len(entries), OUT_H))
    if "--install" in argv:
        n = install(entries)
        print("install: %d 个头文件 -> %s" % (n, FROZEN_DIR))
        print("install: include 块与 %d 条条目 -> %s" % (n, FROZEN_C))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
